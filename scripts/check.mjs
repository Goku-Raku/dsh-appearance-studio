import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const source = fs.readFileSync(path.join(root, 'client.js'), 'utf8');
assert.equal(spawnSync(process.execPath, ['--check', path.join(root, 'client.js')]).status, 0);
assert.equal(pkg.name, 'dsh-appearance-studio');
assert.equal(pkg.private, undefined);
assert.equal(pkg.engines.dsh, '0.2.1-rc.2');
assert.equal(pkg.peerDependencies['@deepseek-ai/dsh'], pkg.engines.dsh);
assert.ok(source.includes("id: '" + pkg.name + "'"));
assert.ok(fs.readFileSync(path.join(root, 'cordis.patch.yml'), 'utf8').includes("name: '" + pkg.name + "'"));
assert.ok(source.includes("const STORE_KEY = 'dsh.appearance-studio.v2'"));
const embedded = source.match(/const BUNDLED_WALLPAPER = "data:image\/jpeg;base64,([^"\r\n]+)";/);
assert.ok(embedded, 'Bundled image marker');
const image = fs.readFileSync(path.join(root, 'assets/bonfire-chu2-manga.jpg'));
assert.deepEqual(Buffer.from(embedded[1], 'base64'), image);
const sha = crypto.createHash('sha256').update(image).digest('hex');
assert.ok(fs.readFileSync(path.join(root, 'assets/README.md'), 'utf8').includes(sha), 'Image attribution hash');
const required = ['index.js','icon.svg','locale/en.json','locale/zh.json','LICENSE','DISCLAIMER.md','SECURITY.md','THIRD-PARTY-NOTICES.md','CHANGELOG.md','theme-sources.json','docs/VALIDATION.md','README.md', ...['zh-TW','zh-CN','en','ja'].map(l=>'README.'+l+'.md')];
for (const file of required) assert.ok(fs.statSync(path.join(root, file)).size > 0, file);
const files=[];function walk(dir){for(const e of fs.readdirSync(dir,{withFileTypes:true})){if(['.git','node_modules','dist'].includes(e.name))continue;const p=path.join(dir,e.name);if(e.isDirectory())walk(p);else files.push(p);}}walk(root);
for(const file of files.filter(f=>f.endsWith('.md'))){const text=fs.readFileSync(file,'utf8');for(const m of text.matchAll(/\]\(([^)]+)\)/g)){let target=m[1].split('#')[0];if(!target||/^(https?:|mailto:)/.test(target))continue;assert.ok(fs.existsSync(path.resolve(path.dirname(file),decodeURIComponent(target))),path.relative(root,file)+' -> '+target);}}
const total=files.reduce((n,f)=>n+fs.statSync(f).size,0);assert.ok(total<10_000_000, 'Public checkout must remain below 10 MB, excluding .git');
console.log(JSON.stringify({result:'passed',runtime:pkg.engines.dsh,files:files.length,bytes:total,wallpaperSha256:sha}));
